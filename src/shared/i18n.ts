/* ───────────── 动态内容翻译（ezPLM 中文数据 → 英文） ───────────── */
const trCache = new Map<string, string>();
try {
  const saved = JSON.parse(localStorage.getItem(KEYS.trCache) ?? '{}') as Record<string, string>;
  for (const [k, v] of Object.entries(saved)) trCache.set(k, v);
} catch { /* 忽略损坏缓存 */ }

let pendingQueue = new Set<string>();
let flushTimer: ReturnType<typeof setTimeout> | null = null;
const listeners = new Set<() => void>();

/**
 * 动态文本（器件描述、AI 建议正文等）的翻译队列。
 *
 * 此前这里会自动调用 AI 翻译，并借用 advisor.analyze 的 Credit —— 用户切个语言
 * 就被悄悄扣费，且计到了错误的类目。现在：
 *   固定 UI 全部走词典表（tr/t），不依赖 AI；
 *   动态文本默认保留原文，只应用已缓存的翻译；
 *   自动翻译已停用。若将来要计费翻译，需单独的 text.translate 操作 + 显式"翻译"按钮。
 */
async function flushQueue() {
  pendingQueue = new Set();
  if (flushTimer) { clearTimeout(flushTimer); flushTimer = null; }
}

const hasCJK = (s: string) => /[\u4e00-\u9fff]/.test(s);

/** 动态文本翻译 hook：en 模式下含中文的文本进入批量翻译队列，完成后自动刷新 */
export function useTranslated(text: string | undefined): string | undefined {
  const lang = useLangStore((s) => s.lang);
  const [, force] = useState(0);
  useEffect(() => {
    if (lang !== 'en' || !text || !hasCJK(text) || trCache.has(text)) return;
    pendingQueue.add(text);
    if (!flushTimer) flushTimer = setTimeout(flushQueue, 300);
    const cb = () => force((x) => x + 1);
    listeners.add(cb);
    return () => { listeners.delete(cb); };
  }, [lang, text]);
  if (lang !== 'en' || !text) return text;
  return trCache.get(text) ?? text;
}

/** 当前语言（非响应式读取，用于格式化等场景） */
export const curLang = (): Lang => useLangStore.getState().lang;

/** 货币符号：中文界面 ¥，英文界面 $ */
export const currencySym = (): string => (curLang() === 'en' ? '$' : '¥');

/**
 * 金额格式化：按界面语言选符号。
 * 注意这里只切换显示符号，不做汇率换算 —— 数值仍是数据源给出的原始金额。
 */
export const fmtPrice = (v: number | undefined | null, digits = 2): string =>
  v == null ? '—' : `${currencySym()}${v.toFixed(digits)}`;
