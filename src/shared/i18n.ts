/**
 * shared/i18n.ts — 中英双语
 *
 * 两层机制：
 * 1) 界面固定文案：内置词典（以中文原文为 key），切换即时、零网络
 * 2) ezPLM 动态内容（器件描述/分类/参数名等中文数据）：英文模式下经 Gemini
 *    批量翻译（300ms 合批 + 会话/localStorage 双缓存，同一文案只翻一次）
 */
import { create } from 'zustand';
import { useEffect, useState } from 'react';
import { KEYS } from './storage';


export type Lang = 'zh' | 'en';

interface LangState {
  lang: Lang;
  toggle: () => void;
  setLang: (l: Lang) => void;
}

export const useLangStore = create<LangState>((set) => ({
  lang: (localStorage.getItem(KEYS.lang) as Lang) || 'zh',
  toggle: () => set((s) => {
    const lang: Lang = s.lang === 'zh' ? 'en' : 'zh';
    localStorage.setItem(KEYS.lang, lang);
    return { lang };
  }),
  setLang: (lang) => { localStorage.setItem(KEYS.lang, lang); set({ lang }); },
}));

